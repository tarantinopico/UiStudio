/**
 * Retrieves catalog metadata for a given WidgetType.
 */
export function getWidgetDefinition(type: WidgetType): WidgetCatalogItem {
  const found = WIDGET_CATALOG.find((item) => item.type === type);
  if (!found) {
    return WIDGET_CATALOG[0];
  }
  return found;
}
