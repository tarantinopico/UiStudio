export function serializeProjectToJson(project: Project): string {
  const payload: SerializedProject = {
    schemaVersion: 1,
    exportedAt: new Date().toISOString(),
    app: 'ComposeStudio',
    project,
  };
  return JSON.stringify(payload, null, 2);
}

export function parseProjectFromJson(rawJson: string): Project {
  const parsed = JSON.parse(rawJson);
  const candidate: Project = parsed.project ? parsed.project : parsed;

  if (
    !candidate ||
    typeof candidate.name !== 'string' ||
    !Array.isArray(candidate.screens) ||
    candidate.screens.length === 0
  ) {
    throw new Error('Invalid ComposeStudio project JSON structure.');
  }

  const now = Date.now();
  return {
    ...candidate,
    id: `proj-${now}-${Math.random().toString(36).slice(2, 7)}`,
    updatedAt: now,
  };
}
